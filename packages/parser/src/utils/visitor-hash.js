/**
 * @fileoverview Privacy-preserving visitor identification utilities
 */

const crypto = require('crypto');

/**
 * Utility class for generating privacy-preserving visitor hashes
 */
class VisitorHasher {
  /**
   * @param {string} [salt] - Salt for hashing (defaults to environment variable or default)
   */
  constructor(salt = null) {
    this.salt = salt || process.env.VISITOR_HASH_SALT || this.generateDefaultSalt();
  }

  /**
   * Generate a default salt based on system characteristics
   * @returns {string} Default salt
   * @private
   */
  generateDefaultSalt() {
    // Use a combination of hostname and a fixed string for consistency
    const os = require('os');
    const hostname = os.hostname();
    const fixedString = 'metrona-analytics-v1';
    return crypto.createHash('sha256').update(`${hostname}:${fixedString}`).digest('hex').substring(0, 32);
  }

  /**
   * Generate a privacy-preserving visitor hash
   * @param {string} ip - IP address
   * @param {string} userAgent - User agent string
   * @returns {string} SHA-256 hash of IP + User Agent + Salt
   */
  generateHash(ip, userAgent) {
    if (!ip || !userAgent) {
      throw new Error('IP address and user agent are required for visitor hashing');
    }

    // Normalize inputs to ensure consistent hashing
    const normalizedIp = this.normalizeIp(ip);
    const normalizedUserAgent = this.normalizeUserAgent(userAgent);
    
    // Combine with salt for privacy
    const combined = `${normalizedIp}:${normalizedUserAgent}:${this.salt}`;
    
    // Generate SHA-256 hash
    return crypto.createHash('sha256').update(combined, 'utf8').digest('hex');
  }

  /**
   * Normalize IP address for consistent hashing
   * @param {string} ip - Raw IP address
   * @returns {string} Normalized IP address
   * @private
   */
  normalizeIp(ip) {
    // Remove any whitespace
    let normalized = ip.trim();
    
    // Handle IPv6 addresses - convert to lowercase
    if (normalized.includes(':')) {
      normalized = normalized.toLowerCase();
    }
    
    // For IPv4, ensure consistent format
    if (normalized.match(/^\d+\.\d+\.\d+\.\d+$/)) {
      // Split and rejoin to normalize (removes leading zeros, etc.)
      const parts = normalized.split('.');
      normalized = parts.map(part => parseInt(part, 10).toString()).join('.');
    }
    
    return normalized;
  }

  /**
   * Normalize user agent string for consistent hashing
   * @param {string} userAgent - Raw user agent string
   * @returns {string} Normalized user agent string
   * @private
   */
  normalizeUserAgent(userAgent) {
    // Remove extra whitespace and normalize case-sensitive parts
    let normalized = userAgent.trim();
    
    // Replace multiple spaces with single space
    normalized = normalized.replace(/\s+/g, ' ');
    
    // Handle common variations in user agent strings
    // Note: We don't want to normalize too aggressively as it might
    // reduce the uniqueness needed for visitor identification
    
    return normalized;
  }

  /**
   * Generate a short hash for display purposes (first 8 characters)
   * @param {string} ip - IP address
   * @param {string} userAgent - User agent string
   * @returns {string} Short hash (8 characters)
   */
  generateShortHash(ip, userAgent) {
    const fullHash = this.generateHash(ip, userAgent);
    return fullHash.substring(0, 8);
  }

  /**
   * Validate that a hash was generated by this hasher
   * @param {string} hash - Hash to validate
   * @param {string} ip - Original IP address
   * @param {string} userAgent - Original user agent
   * @returns {boolean} True if hash is valid
   */
  validateHash(hash, ip, userAgent) {
    try {
      const expectedHash = this.generateHash(ip, userAgent);
      return hash === expectedHash;
    } catch (error) {
      return false;
    }
  }

  /**
   * Get the current salt being used (for debugging/testing)
   * @returns {string} Current salt
   */
  getSalt() {
    return this.salt;
  }

  /**
   * Create a new hasher with a different salt
   * @param {string} newSalt - New salt to use
   * @returns {VisitorHasher} New hasher instance
   */
  withSalt(newSalt) {
    return new VisitorHasher(newSalt);
  }
}

/**
 * Default visitor hasher instance
 */
const defaultHasher = new VisitorHasher();

/**
 * Convenience function for generating visitor hashes
 * @param {string} ip - IP address
 * @param {string} userAgent - User agent string
 * @returns {string} Visitor hash
 */
function generateVisitorHash(ip, userAgent) {
  return defaultHasher.generateHash(ip, userAgent);
}

/**
 * Convenience function for generating short visitor hashes
 * @param {string} ip - IP address
 * @param {string} userAgent - User agent string
 * @returns {string} Short visitor hash
 */
function generateShortVisitorHash(ip, userAgent) {
  return defaultHasher.generateShortHash(ip, userAgent);
}

module.exports = {
  VisitorHasher,
  generateVisitorHash,
  generateShortVisitorHash,
  defaultHasher
};